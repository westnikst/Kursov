#ifndef BFS_H  // Защита от повторного включения
#define BFS_H

#include "maze.h"

// Структура для реализации очереди, необходимой алгоритму BFS
// Очередь используется для хранения клеток, которые нужно посетить
typedef struct {
    int* data;        // Массив для хранения элементов очереди
    int capacity;     // Текущая емкость массива (количество выделенных элементов)
    int head;         // Индекс начала очереди (откуда извлекаем)
    int tail;         // Индекс конца очереди (куда добавляем)
} Queue;

// Функция поиска пути алгоритмом BFS (Breadth-First Search - поиск в ширину)
// Находит кратчайший путь от старта до выхода
// maze - указатель на лабиринт
// time_us - указатель для возврата времени выполнения в микросекундах
// visited_cells - указатель для возврата количества посещенных клеток
// path_length - указатель для возврата длины найденного пути (количество шагов)
// Возвращает 1 если путь найден, 0 если нет
int find_path_bfs(Maze* maze, unsigned long long* time_us,
    int* visited_cells, int* path_length);

#endif