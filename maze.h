#ifndef MAZE_H  // Защита от повторного включения
#define MAZE_H

// Структура, представляющая лабиринт
// Содержит всю информацию о лабиринте: размеры, клетки, координаты старта и выхода
typedef struct {
    int rows;            // Количество строк в лабиринте
    int cols;            // Количество столбцов в лабиринте
    int** cells;         // Двумерный массив клеток лабиринта
    // Значения: 0-проход, 1-стена, 2-старт, 3-выход
    // >=4 - посещенные клетки DFS, <0 - метки BFS
    int start_row;       // Строка стартовой клетки
    int start_col;       // Столбец стартовой клетки
    int exit_row;        // Строка выходной клетки
    int exit_col;        // Столбец выходной клетки
    char* last_stats;    // Строка со статистикой последнего запущенного алгоритма
    // (для сохранения в файл)
} Maze;

// Функции для работы с лабиринтом:

// Создает пустой лабиринт заданного размера (все клетки - стены)
// rows - количество строк, cols - количество столбцов
// Возвращает указатель на созданный лабиринт или NULL при ошибке
Maze* create_maze(int rows, int cols);

// Освобождает память, занятую лабиринтом
// maze - указатель на лабиринт для освобождения
void free_maze(Maze* maze);

// Выводит лабиринт в консоль с рамкой по краям
// maze - указатель на лабиринт для отображения
void print_maze(const Maze* maze);

// Создает лабиринт с использованием алгоритма Прима
// rows - количество строк, cols - количество столбцов
// Возвращает указатель на созданный лабиринт или NULL при ошибке
Maze* generate_maze_prim(int rows, int cols);

#endif